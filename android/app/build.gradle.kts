// Release signing reads four Gradle properties (set in ~/.gradle/gradle.properties,
// never in the repo). When they are absent the release build falls back to the
// debug key so CI can still build.
val storeFileProp = providers.gradleProperty("PA_STORE_FILE").orNull
val storePasswordProp = providers.gradleProperty("PA_STORE_PASSWORD").orNull
val keyAliasProp = providers.gradleProperty("PA_KEY_ALIAS").orNull
val keyPasswordProp = providers.gradleProperty("PA_KEY_PASSWORD").orNull
val hasReleaseKey = listOf(storeFileProp, storePasswordProp, keyAliasProp, keyPasswordProp)
    .all { !it.isNullOrBlank() }

android {
    namespace = "com.jamilcpu.personalautomations"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.jamilcpu.personalautomations"
        minSdk = 26
        targetSdk = 35
        versionCode = 1
        versionName = "0.1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (hasReleaseKey) {
            create("release") {
                storeFile = file(storeFileProp!!)
                storePassword = storePasswordProp
                keyAlias = keyAliasProp
                keyPassword = keyPasswordProp
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            signingConfig = if (hasReleaseKey) {
                signingConfigs.getByName("release")
            } else {
                logger.warn("WARNING: PA_* signing properties not set; signing release with the debug key.")
                signingConfigs.getByName("debug")
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            isReturnDefaultValues = true
        }
    }

    packaging {
        resources {
            excludes += setOf(
                "META-INF/INDEX.LIST",
                "META-INF/io.netty.versions.properties",
                "META-INF/DEPENDENCIES",
                "META-INF/LICENSE*",
                "META-INF/NOTICE*"
            )
        }
    }
}

